    assert.equal(await page.locator('#pc-theme-root').getByText('Vortex-client').count(),0);
    await popup.bringToFront();
    await popup.locator('#background').selectOption('lake');
    await popup.locator('#font').selectOption('mono');
    await popup.locator('#accent').fill('#aabbcc');await popup.locator('#accent').dispatchEvent('change');
    await page.waitForFunction(()=>document.querySelector('main').style.getPropertyValue('--pc-accent')==='#aabbcc');
    assert.match(await page.locator('.forest').getAttribute('src'),/winter-lake/);
    assert.match(await page.locator('main').evaluate(n=>n.style.getPropertyValue('--pc-font')),/Consolas/);
    await popup.locator('#upload').setInputFiles(path.join(extension,'media/winter-lake.png'));
    await page.waitForFunction(()=>document.querySelector('#pc-theme-root').shadowRoot.querySelector('.forest').getAttribute('src').startsWith('data:image/webp;'));
    await page.bringToFront();await page.waitForTimeout(1000);
    await page.screenshot({path:path.join(artifacts,'generic-profile.png'),fullPage:true});
    await page.getByRole('button',{name:'Обычный GitHub ↗'}).click();await root.waitFor({state:'detached'});
    assert.equal(await page.locator('#original').isVisible(),true);
    assert.equal(await page.locator('.p-nickname').textContent(),'demo-dev');
    assert.equal(await page.locator('.pc-native-reveal').count(),0);
    await popup.bringToFront();await popup.getByRole('button',{name:'Сбросить оформление'}).click();
    await root.waitFor();
    assert.equal(await popup.locator('#font').inputValue(),'system');
    await page.evaluate(()=>{document.querySelector('.p-nickname').textContent='demo-next';history.pushState({},'', '/demo-next');window.dispatchEvent(new Event('turbo:load'));});
